import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import {
  approvedFullDetailPublicHeroIds,
  projectApprovedFullDetailRecords,
  validateFullDetailPublicPopulation,
} from './full-detail-public-population-contract.mjs';
import { renderGenerated } from './generate.mjs';

const readJson = async (path) => JSON.parse(await readFile(path, 'utf8'));
const publicationDecision = await readJson('docs/decisions/hero-index-publication.v1.json');
const candidate = await readJson('docs/decisions/hero-15-full-detail-record-field-candidate.v1.json');
const canonical = await readJson('canonical/heroes.v1.json');
const baselineGeneratedText = await readFile('generated/hero-slice.v1.json', 'utf8');
const baselineGenerated = JSON.parse(baselineGeneratedText);

const ownerPaths = [
  'canonical/hero-identities.v1.json',
  'canonical/hero-localizations-ko.v1.json',
  'canonical/job-localizations-ko.v1.json',
  'canonical/hero-exclusive-equipment-relations.v1.json',
  'canonical/exclusive-equipment-localizations-ko.v1.json',
  'canonical/hero-rarities.v1.json',
  'canonical/faction-identities.v1.json',
  'canonical/hero-faction-relations.v1.json',
  'canonical/production-identities.v1.json',
  'canonical/hero-production-relations.v1.json',
  'canonical/hero-talent-star-skills.v1.json',
  'canonical/hero-talent-localizations-ko.v1.json',
  'canonical/faction-localizations-ko.v1.json',
  'canonical/production-localizations-ko.v1.json',
  'canonical/hero-job-relations.v1.json',
  'canonical/sp-job-identities.v1.json',
  'canonical/skills.v1.json',
  'canonical/hero-job-level-raw-stats.v1.json',
];
const owners = await Promise.all(ownerPaths.map(readJson));
const render = (source) => renderGenerated(
  source,
  owners[0], owners[1], owners[2], owners[3], owners[4], owners[5], owners[6], owners[7], owners[8],
  owners[9], owners[10], owners[11], owners[12], owners[13], owners[14], owners[15], owners[16], owners[17],
  publicationDecision,
);

const approvedIds = approvedFullDetailPublicHeroIds(publicationDecision);
assert.deepEqual(approvedIds, baselineGenerated.heroes.map(({ id }) => id));
assert.deepEqual(projectApprovedFullDetailRecords(canonical, publicationDecision).map(({ id }) => id), approvedIds);
assert.equal(render(canonical), baselineGeneratedText, 'current 29-record public output must remain byte-identical');

const futureCanonical = structuredClone(canonical);
futureCanonical.records.push(structuredClone(candidate.record));
const futureGeneratedText = render(futureCanonical);
const futureGenerated = JSON.parse(futureGeneratedText);
assert.equal(futureGeneratedText, baselineGeneratedText, 'an unapproved Canonical Hero 15 candidate must not change Public Generated bytes');
assert.deepEqual(futureGenerated.heroes.map(({ id }) => id), approvedIds);
assert.equal(futureGenerated.heroes.some(({ id }) => id === 15), false);
assert.equal(futureGeneratedText.includes('assets/portraits/hero-15.png'), false);
assert.equal(futureGeneratedText.includes(candidate.record.provenance.id), false);
assert.equal(validateFullDetailPublicPopulation({ canonical: futureCanonical, generated: futureGenerated, publicationDecision }), true);

const rejects = (mutate, pattern) => {
  const value = { canonical: structuredClone(futureCanonical), generated: structuredClone(futureGenerated), publicationDecision: structuredClone(publicationDecision) };
  mutate(value);
  assert.throws(() => validateFullDetailPublicPopulation(value), pattern);
};
const decisionRejects = (mutate, pattern) => {
  const value = structuredClone(publicationDecision);
  mutate(value);
  assert.throws(() => approvedFullDetailPublicHeroIds(value), pattern);
};

const negativeCases = [
  [() => rejects((x) => x.generated.heroes.push(structuredClone(candidate.record)), /IDs must exactly follow/), 'unapproved Hero 15 inserted into public Generated'],
  [() => rejects((x) => { x.generated.heroes = x.generated.heroes.filter(({ id }) => id !== 1); }, /IDs must exactly follow/), 'approved ID omitted'],
  [() => rejects((x) => { x.generated.heroes.reverse(); }, /IDs must exactly follow/), 'approved order changed'],
  [() => rejects((x) => { x.canonical.records = x.canonical.records.filter(({ id }) => id !== 3); }, /no Canonical record/), 'approved Canonical endpoint missing'],
  [() => rejects((x) => { x.canonical.records.push(structuredClone(x.canonical.records[0])); }, /duplicate ID/), 'duplicate Canonical ID'],
  [() => decisionRejects((x) => { x.status = 'PROPOSED'; }, /approved Full Detail endpoint IDs/), 'unapproved decision state'],
  [() => decisionRejects((x) => { x.approvedScope.detailLinkPolicy = 'ALL_CANONICAL_RECORDS'; }, /approved Full Detail endpoint IDs/), 'non-approved endpoint policy'],
  [() => decisionRejects((x) => { x.approvedScope.detailHeroIds.push(15); }, /current approved Full Detail endpoint set changed/), 'Hero 15 added to index target list without Full Detail scope review'],
  [() => decisionRejects((x) => { x.approvedScope.detailHeroIds.push(x.approvedScope.detailHeroIds[0]); }, /approved Full Detail endpoint IDs are missing, malformed/), 'duplicate approved endpoint'],
  [() => decisionRejects((x) => { x.approvedScope.excluded = []; }, /excludes Full Detail presentation expansion/), 'presentation expansion exclusion removed'],
];
for (const [run] of negativeCases) run();

console.log(`Full Detail Public Population tests: PASS (future Canonical 30/Public 29 parity; ${negativeCases.length} negative boundaries)`);
