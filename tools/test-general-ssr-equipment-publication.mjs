import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { validateGeneralSsrPublicationDraft as validate, loadAndValidateGeneralSsrPublicationDraft } from './validate-general-ssr-equipment-publication.mjs';
const read = async p => JSON.parse(await readFile(p, 'utf8'));
const args = { canonical: await read('canonical/general-ssr-equipment.v1.json'), contract: await read('evidence/source/equipment/general-ssr-equipment-population-contract.v1.json'), decision: await read('docs/decisions/general-ssr-equipment-publication.v1.json') };
const original = structuredClone(args);
assert.deepEqual(await loadAndValidateGeneralSsrPublicationDraft(), { status: 'REVIEW_REQUIRED', proposedCount: 198, admission: 'NOT_APPROVED', publication: 'NOT_APPROVED' });
assert.deepEqual(validate(args), { status: 'REVIEW_REQUIRED', proposedCount: 198, admission: 'NOT_APPROVED', publication: 'NOT_APPROVED' });
assert.deepEqual(args, original, 'must not mutate inputs');
const bad = change => { const input = structuredClone(args); change(input); assert.throws(() => validate(input)); };
bad(x => x.decision.excludedIds.pop());
