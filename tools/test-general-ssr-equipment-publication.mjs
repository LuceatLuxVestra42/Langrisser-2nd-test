bad(x => x.decision.excludedIds[0] = 999999);
bad(x => x.decision.excludedIds[0] = x.decision.excludedIds[1]);
bad(x => x.decision.status = 'APPROVED');
bad(x => x.decision.approval = { status: 'APPROVED' });
bad(x => x.decision.source.commit = 'f'.repeat(40));
bad(x => x.decision.surface = 'other surface');
bad(x => x.canonical.records[0].id = 999999);
bad(x => x.canonical.records.push({ ...x.canonical.records[0], id: 999999 }));
bad(x => x.decision.aliasOf = 1);
console.log('General SSR publication draft: positive, immutability and negative tests PASS; activation NOT_APPROVED');
