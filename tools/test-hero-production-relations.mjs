import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { cp, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const source = process.cwd();
const temp = await mkdtemp(join(tmpdir(), 'hero-production-relations-'));
const repo = join(temp, 'repo');
await cp(source, repo, { recursive: true, filter: (path) => !path.split('/').includes('.git') });
const validator = () => spawnSync(process.execPath, ['tools/validate-hero-production-relations.mjs'], { cwd: repo, encoding: 'utf8' });
const generator = () => spawnSync(process.execPath, ['tools/generate.mjs'], { cwd: repo, encoding: 'utf8' });
const diagnostic = (result) => `${result.stdout ?? ''}\n${result.stderr ?? ''}`;
const readJson = async (path) => JSON.parse(await readFile(join(repo, path), 'utf8'));
const readText = async (path) => readFile(join(repo, path), 'utf8');
const writeJson = async (path, value) => writeFile(join(repo, path), `${JSON.stringify(value, null, 2)}\n`);
try {
  let result = validator();
  assert.equal(result.status, 0, diagnostic(result));

  const generatedBefore = await readText('generated/hero-slice.v1.json');
  result = generator();
  assert.equal(result.status, 0, diagnostic(result));
  const generatedAfter = await readText('generated/hero-slice.v1.json');
  assert.equal(generatedAfter, generatedBefore, 'non-presentation relations must leave Generated bytes unchanged');
  const generated = JSON.parse(generatedAfter);
  assert.deepEqual(generated.heroes.map((hero) => hero.id), [1, 3, 5, 6, 8, 10, 11, 12, 13, 14, 25, 27, 28, 32, 52, 53, 55, 67]);
  assert.equal(generated.heroes.some((hero) => [4,7,9,26,29,33,37,40,56,60,89].includes(hero.id)), false);

  const canonicalPath = 'canonical/hero-production-relations.v1.json';
  const inheritedPath = 'evidence/source/configdata/ConfigDataHeroInfo.hero-production-inherited.v1.json';
  const originalCanonical = await readJson(canonicalPath);
  const originalInherited = await readJson(inheritedPath);

  const missing = structuredClone(originalCanonical);
  missing.records.pop();
  await writeJson(canonicalPath, missing);
  result = validator();
  assert.notEqual(result.status, 0, 'missing relation must fail');
  assert.match(diagnostic(result), /exactly 29 admitted edges/);
  await writeJson(canonicalPath, originalCanonical);

  const unknownHero = structuredClone(originalCanonical);
  unknownHero.records.find((row) => row.heroId === 1).heroId = 999;
  await writeJson(canonicalPath, unknownHero);
  result = validator();
  assert.notEqual(result.status, 0, 'unknown Hero endpoint must fail');
  const unknownHeroGenerator = generator();
  assert.notEqual(unknownHeroGenerator.status, 0, 'Generator must reject an unknown Hero identity endpoint');
  await writeJson(canonicalPath, originalCanonical);

  const wrongEndpoint = structuredClone(originalCanonical);
  wrongEndpoint.records.find((row) => row.heroId === 1).productionId = 999;
  await writeJson(canonicalPath, wrongEndpoint);
  result = validator();
  assert.notEqual(result.status, 0, 'unknown Production endpoint must fail');
  assert.match(diagnostic(result), /unresolved endpoint|differs from its ID-specific evidence/);
  await writeJson(canonicalPath, originalCanonical);

  const wrongProvenance = structuredClone(originalCanonical);
  wrongProvenance.records.find((row) => row.heroId === 1).provenance = 'evidence/source/hero-origin-dictionary.v1.json#records/productionId=3';
  await writeJson(canonicalPath, wrongProvenance);
  result = validator();
  assert.notEqual(result.status, 0, 'dictionary evidence must not support a relation claim');
  assert.match(diagnostic(result), /correct HeroBelongProduction evidence/);
  await writeJson(canonicalPath, originalCanonical);

  const duplicate = structuredClone(originalCanonical);
  duplicate.records.push(structuredClone(duplicate.records[0]));
  await writeJson(canonicalPath, duplicate);
  result = validator();
  assert.notEqual(result.status, 0, 'duplicate relation must fail');
  assert.match(diagnostic(result), /exactly 29 admitted edges/);
  await writeJson(canonicalPath, originalCanonical);

  const unsupportedProductionEndpoint = structuredClone(originalCanonical);
  unsupportedProductionEndpoint.records.find((row) => row.heroId === 60).productionId = 9;
  await writeJson(canonicalPath, unsupportedProductionEndpoint);
  result = validator();
  assert.notEqual(result.status, 0, 'unknown Production endpoint for Hero 60 must fail');
  await writeJson(canonicalPath, originalCanonical);

  const wrongSource = structuredClone(originalInherited);
  wrongSource.records.find((row) => row.heroId === 1).projectedArray = [4];
  await writeJson(inheritedPath, wrongSource);
  result = validator();
  assert.notEqual(result.status, 0, 'source pointer mismatch must fail');
  assert.match(diagnostic(result), /inherited Production pointer drift/);
  await writeJson(inheritedPath, originalInherited);

  const badLocator = structuredClone(originalInherited);
  badLocator.records.find((row) => row.heroId === 3).legacyLocator = 'data/validation/other.json#heroes[heroId=3]/productionId';
  await writeJson(inheritedPath, badLocator);
  result = validator();
  assert.notEqual(result.status, 0, 'Legacy locator drift must fail');
  assert.match(diagnostic(result), /Legacy relation locator drift/);

  process.stdout.write('Hero–Production relation tests: PASS (29-edge owner, source/provenance negatives, Production ID 8 relation admission, Generator endpoint validation and Generated byte parity)\\n');
} finally {
  await rm(temp, { recursive: true, force: true });
}
